// npx --package @playwright/cli playwright-cli -s=selection run-code --filename tests/terminalSelection.browser.js
async (page) => {
  if (!['127.0.0.1','localhost'].includes(new URL(page.url()).hostname)) throw new Error('Local fixture only');
  const check=(v,m)=>{if(!v)throw new Error(m);};
  let socket,sessionId; const writes=[];
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false});
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.setViewportSize({width:1280,height:820});
  await page.route('**/api/load_state',r=>r.fulfill({json:{projects:[],activeProjectId:null}}));
  await page.route('**/api/events_ticket',r=>r.fulfill({json:{ticket:null}}));
  await page.routeWebSocket('**/api/events*',ws=>{socket=ws;});
  await page.route('**/api/terminal_*',async r=>{
    const command=r.request().url().split('/').pop(),body=r.request().postDataJSON();
    if(command==='terminal_start')sessionId=body.sessionId;
    if(command==='terminal_write')writes.push(body.data);
    await r.fulfill(command==='terminal_start'?{json:{sessionId,shell:'Selection fixture',cwd:'D:/selection'}}:{status:204});
  });
  await page.evaluate(()=>{localStorage.setItem('code-terminal-view-mode','terminal');localStorage.setItem('opencode-workbench.mobile-chrome-hidden','false');});
  await page.reload();
  await page.locator('.xterm-rows').waitFor();
  for(let i=0;i<40&&(!socket||!sessionId);i++)await page.waitForTimeout(100);
  check(socket&&sessionId,'Fixture ready');
  const output=async data=>{socket.send(JSON.stringify({type:'terminalOutput',payload:{sessionId,data}}));await page.waitForTimeout(250);};
  const sample='copy this exact part';
  await output('\x1b[2J\x1b[H'+sample+'\r\n  const total = 12345678901234567890.123456;\r\n中文输出 😀\r\n');
  const actions=page.getByRole('group',{name:'选中文字操作',exact:true});
  const copy=page.getByRole('button',{name:'复制到剪贴板',exact:true});
  const paste=page.getByRole('button',{name:'粘贴到输入栏',exact:true});
  const input=page.getByRole('textbox',{name:'输入内容',exact:true});
  check(!await actions.count()&&!await page.getByRole('button',{name:'选择复制',exact:true}).count(),'No permanent entry or unselected actions');
  async function point(col,row=0){return page.locator('.xterm-rows').evaluate((el,{col,row})=>{const rows=el.children,r=rows[row].getBoundingClientRect();const text=rows[0].querySelector('span');const range=document.createRange();range.selectNodeContents(text);const b=range.getBoundingClientRect();return{x:r.left+col*b.width/text.textContent.length,y:r.top+r.height/2};},{col,row});}
  async function drag(start,end,row=0){await page.waitForTimeout(500);const a=await point(start,row),b=await point(end,row);await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(b.x,b.y,{steps:12});await page.mouse.up();await copy.waitFor({timeout:5000});}
  await drag(5,15);
  await copy.click();
  check(await page.evaluate(()=>navigator.clipboard.readText())==='this exact','Desktop drag copies substring');
  check(writes.length===0,'Copy sends no input');
  check((await actions.innerText()).includes('已复制'),'Success feedback');
  await page.screenshot({path:'output/playwright/selection-desktop.png'});
  await page.evaluate(()=>{window.savedClipboard=navigator.clipboard;Object.defineProperty(navigator,'clipboard',{configurable:true,value:undefined});});
  await copy.click();
  check(await page.evaluate(()=>window.savedClipboard.readText())==='this exact','HTTP fallback copies selected text');
  await page.evaluate(()=>{window.savedExec=document.execCommand;document.execCommand=()=>false;});
  await copy.click();await page.waitForTimeout(100);
  check((await actions.innerText()).includes('复制未成功'),'Denied copy has actionable feedback');
  await page.evaluate(()=>{document.execCommand=window.savedExec;Object.defineProperty(navigator,'clipboard',{configurable:true,value:window.savedClipboard});});
  await paste.click();
  check(await input.inputValue()==='this exact'&&writes.length===0,'Paste opens composer and never submits');
  await input.fill('before AFTER');await input.evaluate(el=>el.setSelectionRange(7,7));
  await drag(5,15);await paste.click();
  check(await input.inputValue()==='before this exactAFTER','Paste preserves both sides of draft');
  await drag(5,15);writes.length=0;await page.keyboard.press('Control+c');await page.waitForTimeout(80);
  check(writes.length===0&&await page.evaluate(()=>navigator.clipboard.readText())==='this exact','Selected Ctrl+C copies');
  await page.waitForTimeout(550);await page.mouse.click((await point(2,5)).x,(await point(2,5)).y);await page.keyboard.press('Control+c');await page.waitForTimeout(80);
  check(writes.includes('\x03'),'Unselected Ctrl+C interrupts');
  await output('\x1b[?1049h\x1b[?1000h\x1b[?1006h\x1b[2J\x1b[H'+sample+'\r\n  code line\r\n');
  writes.length=0;await drag(5.2,14.2);await copy.click();
  check(await page.evaluate(()=>navigator.clipboard.readText())==='this exact','TUI drag selects exact substring');
  check(writes.length===0,'TUI drag does not send mouse commands');
  await page.waitForTimeout(550);await page.mouse.click((await point(2,5)).x,(await point(2,5)).y);await page.waitForTimeout(100);
  check(writes.some(s=>s.includes('\x1b[<0;')),'TUI simple click remains supported');
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  for(const [width,height] of [[390,844],[360,740],[320,568],[884,1104],[360,420]]){
    await page.setViewportSize({width,height});await page.waitForTimeout(200);
    await output('\x1b[2J\x1b[H'+sample+'\r\n中文输出 😀\r\n');
    writes.length=0;
    const p=await point(6);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[p]});await page.waitForTimeout(550);
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await copy.waitFor();
    check(await page.getByRole('button',{name:'调整选区终点'}).count()===1,'Long press provides selection handles');
    await copy.click();
    check(await page.evaluate(()=>navigator.clipboard.readText())==='this','Long press selects touched word');
    const bounds=await actions.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight&&el.scrollWidth<=el.clientWidth&&[...el.querySelectorAll('button')].every(b=>b.getBoundingClientRect().height>=44);});
    check(bounds,'Selection actions stay inside viewport '+width+'x'+height);
    await page.screenshot({path:'output/playwright/selection-'+width+'x'+height+'.png'});
    check(writes.length===0,'Touch select/copy sends no TUI input');
    await paste.click();check((await input.inputValue()).includes('this'),'Touch paste inserts draft');
  }
  // Ordinary quick swipes retain program scrolling; long-press drag changes selection.
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
  await output('\x1b[2J\x1b[H'+sample+'\r\nsecond selectable line\r\n');
  writes.length=0;
  const a=await point(6),b=await point(14.2);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[a]});await page.waitForTimeout(550);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[b]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await copy.click();check(await page.evaluate(()=>navigator.clipboard.readText())==='this exact','Long press drag expands arbitrary range');
  check(writes.length===0,'Long drag does not scroll TUI');
  const handle=page.getByRole('button',{name:'调整选区终点'}),rect=await handle.boundingBox(),target=await point(19.2);
  await page.mouse.move(rect.x+22,rect.y+22);await page.mouse.down();await page.mouse.move(target.x,target.y+12,{steps:10});await page.mouse.up();
  await copy.click();check(await page.evaluate(()=>navigator.clipboard.readText())==='this exact part','Handle adjusts selection endpoint');
  await paste.click();
  const sw=await point(3,5);writes.length=0;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[sw]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:sw.x,y:sw.y+100}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(150);
  check(writes.some(s=>s.includes('\x1b[<64;'))&&!await actions.count(),'Quick swipe still scrolls TUI without selection');
  // Native dialog selection gets the same actions and preserves multiline text.
  await page.getByRole('button',{name:'设置',exact:true}).click();await page.getByRole('button',{name:'对话',exact:true}).click();
  if(await page.locator('.settings-popover').isVisible())await page.getByRole('button',{name:'设置',exact:true}).click();
  await input.fill('selected dialog text');await input.press('Enter');await page.waitForTimeout(250);writes.length=0;
  const bubble=page.locator('.terminal-dialog-bubble').filter({hasText:'selected dialog text'}).last();
  await bubble.evaluate(el=>{const r=document.createRange();r.setStart(el.firstChild,0);r.setEnd(el.firstChild,8);const s=window.getSelection();s.removeAllRanges();s.addRange(r);});
  await copy.click();check(await page.evaluate(()=>navigator.clipboard.readText())==='selected','Dialog selected copy');
  await paste.click();check(await input.inputValue()==='selected'&&writes.length===0,'Dialog selected paste never submits');
  await input.fill('第一行中文 😀\n  const amount = 12345678901234567890.123456;\n'+ 'continuous_code_'.repeat(30));
  await input.press('Enter');await page.waitForTimeout(250);writes.length=0;
  const longBubble=page.locator('.terminal-dialog-bubble').filter({hasText:'第一行中文'}).last();
  await longBubble.evaluate(el=>{const r=document.createRange();r.selectNodeContents(el);const s=window.getSelection();s.removeAllRanges();s.addRange(r);});
  await copy.click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).replaceAll('\r\n','\n')===await longBubble.textContent(),'Multiline Unicode, indentation, long codes and amount precision preserved');
  await page.screenshot({path:'output/playwright/selection-dialog-long.png'});
  await page.evaluate(()=>{const shell=document.querySelector('.shell');shell.style.zoom='1.5';shell.style.setProperty('--app-viewport-height',innerHeight/1.5+'px');});
  await page.waitForTimeout(200);
  await page.screenshot({path:'output/playwright/selection-zoom150.png'});
  check(await actions.evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;}),'150% zoom action boundaries');
  await page.evaluate(()=>{const shell=document.querySelector('.shell');shell.style.zoom='';shell.style.removeProperty('--app-viewport-height');});
  await page.keyboard.press('Escape');
  console.log('PASS: desktop/TUI drag, phone long press and handles, exact copy, HTTP fallback/denial, paste preserving draft, no submission, Ctrl+C, TUI clicks/swipes, dialog selection and viewport boundaries.');
  return {passed:true,coverage:'desktop/TUI selection; phone long press/handles; copy/fallback/denial; draft insertion; shortcuts; TUI click/scroll; dialog Unicode/multiline; viewport and 150% zoom'};
}
