async (page) => {
  if(!['127.0.0.1','localhost'].includes(new URL(page.url()).hostname))throw new Error('Local fixture only');
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const projects=['a','b'].map(id=>({id,name:'Cache project '+id,path:'D:/cache/'+id,status:'idle',lastOpenedAt:0}));
  let active='a',phase='initial',calls={a:0,b:0};
  const state=()=>({projects,activeProjectId:active});
  const item=(id,title=id)=>({id,title,cwd:'D:/cache/a',updatedAt:Date.now()});
  const original=Array.from({length:12},(_,i)=>item('a-'+i,i<2?'同名会话':'历史会话 '+i));
  const recent=[item('a-0','已重命名的历史会话'),...Array.from({length:11},(_,i)=>item('new-'+i,'continuous_session_name_'.repeat(8)+i))];
  await page.setViewportSize({width:1280,height:850});
  await page.route('**/api/load_state',r=>r.fulfill({json:state()}));
  await page.route('**/api/initial_project_id',r=>r.fulfill({json:null}));
  await page.route('**/api/set_active_project',r=>{active=r.request().postDataJSON().projectId;return r.fulfill({json:state()});});
  await page.route('**/api/list_codex_sessions',async r=>{
    const id=r.request().postDataJSON().projectId;calls[id]++;
    await new Promise(resolve=>setTimeout(resolve,350));
    if(phase==='fail')return r.fulfill({status:503,body:'temporary history failure'});
    return r.fulfill({json:id==='b'?[item('b-only','B 的独立会话')]:phase==='initial'?original:recent});
  });
  await page.route('**/api/events_ticket',r=>r.fulfill({json:{ticket:null}}));
  await page.routeWebSocket('**/api/events*',()=>{});
  await page.route('**/api/terminal_*',r=>{
    const command=r.request().url().split('/').pop(),body=r.request().postDataJSON();
    return r.fulfill(command==='terminal_start'?{json:{sessionId:body.sessionId,shell:'Cache fixture',cwd:'D:/cache/'+active}}:{status:204});
  });
  await page.evaluate(()=>{for(const key of Object.keys(localStorage))if(key.startsWith('opencode-workbench.codex-sessions.v1:'))localStorage.removeItem(key);});
  await page.reload();
  const rows=()=>page.locator('.project-sessions .project-session-item');
  await rows().nth(11).waitFor();
  check(calls.a===1,'Initial history requested once');
  await page.locator('[data-project-id="b"] .project-select').click();
  await page.getByText('B 的独立会话',{exact:true}).waitFor();check(calls.b===1,'B has independent history');
  await page.locator('[data-project-id="a"] .project-select').click();await rows().nth(11).waitFor();
  await page.locator('[data-project-id="a"] .project-select').click();await page.locator('[data-project-id="a"] .project-select').click();
  check(calls.a===1,'Project switching and expanding use cache');
  await page.reload();await rows().nth(11).waitFor();await page.waitForTimeout(400);
  check(calls.a===1,'Browser reload uses persistent cache');
  check(await rows().filter({hasText:'同名会话'}).count()===2,'Same title distinct IDs retained');
  phase='recent';await page.getByTitle('刷新项目',{exact:true}).click();
  await page.getByText('正在读取...',{exact:true}).waitFor();
  check(await rows().count()===12,'Refreshing does not hide cached rows');
  await rows().nth(22).waitFor();check(calls.a===2,'Manual refresh requests new history');
  check(await rows().count()===23,'Loaded records beyond latest twelve are retained');
  check(await page.getByText('已重命名的历史会话',{exact:true}).count()===1,'Refresh updates matching ID');
  phase='fail';await page.getByTitle('刷新项目',{exact:true}).click();
  await page.getByText('读取失败，点击重试',{exact:true}).waitFor();
  check(await rows().count()===23,'Failed refresh retains history');
  phase='recent';await page.getByText('读取失败，点击重试',{exact:true}).click();
  await page.waitForTimeout(500);check(await rows().count()===23&&!await page.getByText('读取失败，点击重试',{exact:true}).count(),'Retry merges without duplicates');
  await page.screenshot({path:'output/playwright/history-cache-desktop.png'});
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250);
  if(!await rows().first().isVisible())await page.locator('.mobile-project-menu-button:visible').click();
  check(await rows().count()===23,'Touch drawer retains loaded history');
  check(await rows().first().evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&el.scrollWidth<=el.clientWidth;}),'History row fits mobile drawer');
  await page.screenshot({path:'output/playwright/history-cache-mobile.png'});
  return {passed:true,calls,retained:23,persistent:true,failedRefreshPreserved:true};
}
