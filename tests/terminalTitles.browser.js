async (page) => {
  if (!['127.0.0.1','localhost'].includes(new URL(page.url()).hostname)) throw new Error('Local fixture only');
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const project={id:'title-project',name:'opencode-workbench',path:'D:/project/opencode-workbench',status:'idle',lastOpenedAt:0};
  const starts=[],writes=[],errors=[];let socket;
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1280,height:850});
  await page.route('**/api/load_state',r=>r.fulfill({json:{projects:[project],activeProjectId:project.id}}));
  await page.route('**/api/initial_project_id',r=>r.fulfill({json:null}));
  await page.route('**/api/list_codex_sessions',r=>r.fulfill({json:[{id:'11111111-2222-4333-8444-555555555555',title:'恢复历史会话名称',cwd:project.path,updatedAt:1}]}));
  await page.route('**/api/events_ticket',r=>r.fulfill({json:{ticket:null}}));
  await page.routeWebSocket('**/api/events*',ws=>{socket=ws;});
  await page.route('**/api/terminal_*',async r=>{
    const command=r.request().url().split('/').pop(),body=r.request().postDataJSON();
    if(command==='terminal_start')starts.push(body);
    if(command==='terminal_write')writes.push(body);
    await r.fulfill(command==='terminal_start'?{json:{sessionId:body.sessionId,shell:'Title fixture',cwd:project.path}}:{status:204});
  });
  await page.evaluate(()=>{localStorage.removeItem('opencode-workbench.session-names');localStorage.setItem('code-terminal-view-mode','terminal');localStorage.setItem('opencode-workbench.mobile-chrome-hidden','false');});
  await page.reload();await page.locator('.terminal-cell.active .xterm-rows').waitFor();
  await page.waitForTimeout(600);
  const first=starts.at(-1).sessionId;
  const esc=String.fromCharCode(27),bell=String.fromCharCode(7);
  const output=async(id,title)=>{socket.send(JSON.stringify({type:'terminalOutput',payload:{sessionId:id,data:esc+']0;'+title+bell}}));await page.waitForTimeout(200);};
  const activeTitle=()=>page.locator('.terminal-cell.active .terminal-cell-title');
  const field=page.getByRole('textbox',{name:'输入内容',exact:true});
  if(!await field.isVisible())await page.getByTitle('展开辅助输入区',{exact:true}).click();
  const send=async text=>{await field.fill(text);await field.press('Enter');await page.waitForTimeout(200);};
  await output(first,'⠋ 修复登录问题 | opencode-workbench');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 修复登录问题','Project and session names both shown');
  await send('/rename 新的真实会话名');
  check(writes.some(w=>w.sessionId===first&&w.data.includes('/rename 新的真实会话名')),'Native /rename reaches the original PTY');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 修复登录问题','Unconfirmed rename does not pretend success');
  await output(first,'新的真实会话名 | opencode-workbench');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 新的真实会话名','Confirmed Codex title syncs');
  writes.length=0;await send('/tab-name 我的显示名称');
  check(writes.length===0&&await activeTitle().getAttribute('title')==='opencode-workbench · 我的显示名称','Workbench rename stays local and preserves project');
  check(await page.evaluate(id=>JSON.parse(localStorage.getItem('opencode-workbench.session-names'))[id].custom,first)==='我的显示名称','Alias is saved against the exact PTY for background reopening');
  await output(first,'[ ! ] Action Required | 后续真实名称 | opencode-workbench');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 我的显示名称','Custom name survives automatic updates');
  await send('/tab-name --auto');
  check(writes.length===0&&await activeTitle().getAttribute('title')==='opencode-workbench · 后续真实名称','Auto reset restores latest actual title');
  await send('/title');
  check(writes.some(w=>w.data.includes('/title')),'Codex /title is not intercepted');
  await output(first,'名字中含 | 分隔符 | opencode-workbench');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 名字中含 | 分隔符','Only the known trailing project is removed');
  const count=starts.length;
  await page.getByTitle('新建终端',{exact:true}).click();
  for(let i=0;i<50&&starts.length===count;i++)await page.waitForTimeout(100);
  const second=starts.at(-1).sessionId;check(second!==first,'Second terminal started');
  await output(second,'第二个会话 | opencode-workbench');
  await output(first,'第一个会话更新 | opencode-workbench');
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 第二个会话','Background title never renames active terminal');
  check(await page.getByRole('tab',{name:'opencode-workbench · 第一个会话更新',exact:true}).count()===1,'Background title updates its own tab');
  await send('/tab-name '+ '这是很长的会话名称含continuous_code_1234567890'.repeat(5));
  const full=await activeTitle().getAttribute('title');
  check(full.startsWith('opencode-workbench · '),'Long custom title keeps project');
  await page.screenshot({path:'output/playwright/terminal-titles-desktop.png'});
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  for(const width of [390,360]){
    await page.setViewportSize({width,height:844});await page.waitForTimeout(250);
    check(await page.locator('.terminal-cell.active .terminal-title-project').textContent()==='opencode-workbench','Project stays visible on touch');
    check(await activeTitle().evaluate(el=>{const r=el.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&el.scrollWidth<=el.clientWidth;}),'Title stays within cell '+width);
    check(await page.locator('.terminal-cell.active .terminal-title-name').evaluate(el=>el.clientWidth>0),'Session retains allocated width');
    check(await page.locator('.terminal-cell.active .terminal-title-project').evaluate(el=>el.clientWidth>=el.parentElement.clientWidth*0.3),'Long session name must not squeeze project to one character');
    await page.screenshot({path:'output/playwright/terminal-titles-'+width+'.png'});
  }
  await page.evaluate(()=>{const shell=document.querySelector('.shell');shell.style.zoom='1.5';shell.style.setProperty('--app-viewport-height',innerHeight/1.5+'px');});
  await page.waitForTimeout(200);
  check(await activeTitle().evaluate(el=>el.getBoundingClientRect().right<=innerWidth),'Enlarged title stays within viewport');
  await page.screenshot({path:'output/playwright/terminal-titles-zoom.png'});
  await page.evaluate(()=>{const shell=document.querySelector('.shell');shell.style.zoom='';shell.style.removeProperty('--app-viewport-height');});
  check(errors.length===0,'No browser errors');
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false});
  await page.setViewportSize({width:1280,height:850});await page.waitForTimeout(200);
  // Restoring a known thread starts with its exact history label before any OSC arrives.
  const history=page.locator('.project-session-item').filter({hasText:'恢复历史会话名称'});
  if(!await history.isVisible())await page.locator('.project-select').click();
  const beforeResume=starts.length;
  await history.click();
  for(let i=0;i<50&&starts.length===beforeResume;i++)await page.waitForTimeout(100);
  await page.waitForTimeout(350);
  check(await activeTitle().getAttribute('title')==='opencode-workbench · 恢复历史会话名称','Resume title comes from exact clicked history session');
  check(writes.some(w=>w.data.includes('codex resume 11111111-2222-4333-8444-555555555555')),'History resume keeps exact thread ID');
  await output(starts.at(-1).sessionId,'opencode-workbench');
  check(!(await activeTitle().getAttribute('title')).includes('恢复历史会话名称'),'Explicit unnamed title clears previous history name');
  return {passed:true,nativeRename:true,workbenchRename:true,projectsPreserved:true,multipleSessions:true,viewports:[1280,390,360]};
}
